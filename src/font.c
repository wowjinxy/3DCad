struct Font {
    int pixel_width;
    int pixel_height;
    size_t bytes_per_glyph;
    uint8_t* glyphs;
};

static uint32_t next_utf8_codepoint(const unsigned char** cursor) {
    const unsigned char* text = *cursor;
    const uint32_t first = text[0];

    if (first < 0x80u) {
        *cursor = text + 1;
        return first;
    }

    if (first >= 0xc2u && first <= 0xdfu &&
        (text[1] & 0xc0u) == 0x80u) {
        *cursor = text + 2;
        return ((first & 0x1fu) << 6) | (text[1] & 0x3fu);
    }

    if (first >= 0xe0u && first <= 0xefu &&
        (text[1] & 0xc0u) == 0x80u &&
        (text[2] & 0xc0u) == 0x80u &&
        !(first == 0xe0u && text[1] < 0xa0u) &&
        !(first == 0xedu && text[1] >= 0xa0u)) {
        *cursor = text + 3;
        return ((first & 0x0fu) << 12) |
               ((uint32_t)(text[1] & 0x3fu) << 6) |
               (text[2] & 0x3fu);
    }

    if (first >= 0xf0u && first <= 0xf4u &&
        (text[1] & 0xc0u) == 0x80u &&
        (text[2] & 0xc0u) == 0x80u &&
        (text[3] & 0xc0u) == 0x80u &&
        !(first == 0xf0u && text[1] < 0x90u) &&
        !(first == 0xf4u && text[1] >= 0x90u)) {
        *cursor = text + 4;
        return ((first & 0x07u) << 18) |
               ((uint32_t)(text[1] & 0x3fu) << 12) |
               ((uint32_t)(text[2] & 0x3fu) << 6) |
               (text[3] & 0x3fu);
    }

    /* Consume exactly one byte on malformed input so progress is guaranteed
       without reading arbitrary replacement glyph indices. */
    *cursor = text + 1;
    return (uint32_t)'?';
}

static unsigned int glyph_index_for_codepoint(uint32_t codepoint) {
    if (codepoint < FONT_FIRST_GLYPH || codepoint > FONT_LAST_GLYPH) {
        return FONT_REPLACEMENT_GLYPH;
    }
    return (unsigned int)(codepoint - FONT_FIRST_GLYPH);
}

Font* font_create_default(int point_size, float display_scale) {
    Font* font;
    unsigned int glyph;
    size_t row_bytes;
    int pixel_y;

    if (point_size <= 0) return NULL;
    if (!(display_scale > 0.0f) || display_scale > 8.0f) display_scale = 1.0f;

    font = (Font*)calloc(1, sizeof(*font));
    if (!font) return NULL;
    font->pixel_width = (int)((float)FONT_LOGICAL_WIDTH * display_scale + 0.5f);
    font->pixel_height = (int)((float)FONT_LOGICAL_HEIGHT * display_scale + 0.5f);
    if (font->pixel_width < 1) font->pixel_width = 1;
    if (font->pixel_height < 1) font->pixel_height = 1;
    row_bytes = ((size_t)font->pixel_width + 7u) / 8u;
    if ((size_t)font->pixel_height > SIZE_MAX / row_bytes) {
        free(font);
        return NULL;
    }
    font->bytes_per_glyph = row_bytes * (size_t)font->pixel_height;
    if (font->bytes_per_glyph > SIZE_MAX / FONT_GLYPH_COUNT) {
        free(font);
        return NULL;
    }
    font->glyphs = (uint8_t*)calloc(FONT_GLYPH_COUNT,
                                    font->bytes_per_glyph);
    if (!font->glyphs) {
        free(font);
        return NULL;
    }

    for (glyph = 0; glyph < FONT_GLYPH_COUNT; ++glyph) {
        uint8_t* destination = font->glyphs +
                               (size_t)glyph * font->bytes_per_glyph;
        for (pixel_y = 0; pixel_y < font->pixel_height; ++pixel_y) {
            int logical_y = (int)((float)pixel_y / display_scale);
            int pixel_x;
            uint8_t source_row;
            if (logical_y >= FONT_LOGICAL_HEIGHT)
                logical_y = FONT_LOGICAL_HEIGHT - 1;
            source_row = basic_latin_8x8[glyph][7 - logical_y / 2];
            for (pixel_x = 0; pixel_x < font->pixel_width; ++pixel_x) {
                int logical_x = (int)((float)pixel_x / display_scale);
                if (logical_x >= FONT_LOGICAL_WIDTH)
                    logical_x = FONT_LOGICAL_WIDTH - 1;
                if (source_row & (uint8_t)(1u << logical_x)) {
                    destination[(size_t)pixel_y * row_bytes +
                                (size_t)pixel_x / 8u] |=
                        (uint8_t)(1u << (pixel_x & 7));
                }
            }
        }
    }

    return font;
}

void font_destroy(Font* font) {
    if (!font) return;
    free(font->glyphs);
    free(font);
}

int font_height(const Font* font) {
    (void)font;
    return FONT_LOGICAL_HEIGHT;
}

int font_measure(const Font* font, const char* text) {
    const unsigned char* cursor = (const unsigned char*)text;
    int width = 0;
    (void)font;

    if (!cursor) return 0;
    while (*cursor) {
        (void)next_utf8_codepoint(&cursor);
        if (width > INT_MAX - FONT_LOGICAL_WIDTH) return INT_MAX;
        width += FONT_LOGICAL_WIDTH;
    }
    return width;
}

void font_draw(const Font* font, int x, int y, const char* text, uint8_t gray) {
    const unsigned char* cursor = (const unsigned char*)text;

    if (!font || !cursor) return;

    /* Bitmap unpacking is client state; all other touched state is server
       state. Preserve both so text can be inserted safely between the legacy
       editor's 2D and 3D fixed-function passes. */
    glPushAttrib(GL_ALL_ATTRIB_BITS);
    glPushClientAttrib(GL_CLIENT_PIXEL_STORE_BIT);

    glDisable(GL_ALPHA_TEST);
    glDisable(GL_BLEND);
    glDisable(GL_CULL_FACE);
    glDisable(GL_DEPTH_TEST);
    glDisable(GL_FOG);
    glDisable(GL_LIGHTING);
    glDisable(GL_TEXTURE_1D);
    glDisable(GL_TEXTURE_2D);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glPixelStorei(GL_UNPACK_LSB_FIRST, GL_TRUE);
    glColor3ub(gray, gray, gray);
    glRasterPos2i(x, y + FONT_LOGICAL_HEIGHT);

    while (*cursor) {
        const uint32_t codepoint = next_utf8_codepoint(&cursor);
        const unsigned int glyph = glyph_index_for_codepoint(codepoint);
        glBitmap(font->pixel_width, font->pixel_height,
                 0.0f, 0.0f,
                 (GLfloat)font->pixel_width, 0.0f,
                 font->glyphs +
                     (size_t)glyph * font->bytes_per_glyph);
    }

    glPopClientAttrib();
    glPopAttrib();
}
